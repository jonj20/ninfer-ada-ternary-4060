// Mean-key capture staging (kvmem-port.md 2.6 stage 4b). The Program owns these buffers and binds
// them per round; the model execution reduces pre-RoPE keys into them and stages the host copy.
//
// `SequenceBatch` is the ordinary decode shape: every lane is one token, so each lane's range
// covers exactly one block and its staging column is fixed at `lane * key_width`. That fixed
// layout is what lets the reduction and its download be captured into a CUDA graph - the addresses
// are Program-owned and stable, and the block identity the reduction derives from its position
// argument is invariant for a one-token range, so the captured constant stays correct on replay.
// `Single` is the prefill shape: one contiguous sequence, real absolute positions, one recorded
// segment per reduced call so a multi-call chunk keeps every segment's identity.
enum class KVMemCaptureMode : std::uint8_t { None, Single, SequenceBatch };

struct KVMemCaptureSegment {
    std::int32_t first_position = 0;
    std::uint32_t tokens        = 0;
    std::uint32_t offset        = 0;  // float offset into the staging buffer
};

// Program-owned capture target. `sums` and `host` both hold `capacity_blocks` columns of
// `key_width` floats; `segments` receives one entry per reduced call in `Single` mode and is
// unused in `SequenceBatch` mode, whose layout the Program derives from the lane order.
// `segment_count` is traversal output: the execution writes it as it fills `segments`, and the
// Program reads it after the traversal synchronizes.
struct KVMemCaptureTarget {
    float* sums              = nullptr;
    float* host              = nullptr;
    KVMemCaptureSegment* segments          = nullptr;
    std::uint32_t segment_capacity         = 0;
    std::uint32_t segment_count            = 0;  // segments written this traversal
    std::uint32_t capacity_blocks          = 0;
    std::uint32_t key_width                = 0;
    std::uint32_t block_tokens             = 0;
    KVMemCaptureMode mode                  = KVMemCaptureMode::None;
    // Compact Full Attention index to capture at. run_layers numbers only Full Attention blocks,
    // so index 0 is the model's first Full Attention layer: any single layer is self-consistent
    // because the retrieval query is a captured mean rather than a live query vector.
    std::int32_t capture_layer = 0;
};

